import type { Unit, WeatherBundle } from "../types/weather";
import { toUnit } from "./format";

export async function shareWeather(b: WeatherBundle, unit: Unit) {
  const text = `${b.place.name}: ${toUnit(b.current.temp, unit)}°${unit}, ${b.current.info.label}. Feels like ${toUnit(b.current.apparent, unit)}°.`;
  const data = { title: "Skyward Weather", text, url: location.href };
  if (navigator.share) {
    try {
      await navigator.share(data);
      return;
    } catch {
      /* user cancelled */
    }
  }
  await navigator.clipboard.writeText(`${text} ${location.href}`);
  alert("Weather copied to clipboard!");
}

/** Generates a printable weather report (opens the browser print/PDF dialog). */
export function downloadReport(b: WeatherBundle, unit: Unit) {
  const rows = b.daily
    .map(
      (d, i) =>
        `<tr><td>${i === 0 ? "Today" : new Date(d.date).toLocaleDateString([], { weekday: "long" })}</td><td>${d.info.label}</td><td>${toUnit(d.max, unit)}° / ${toUnit(d.min, unit)}°</td><td>${d.precip}%</td></tr>`,
    )
    .join("");
  const html = `<!doctype html><html><head><meta charset="utf-8"><title>Weather Report — ${b.place.name}</title>
  <style>body{font-family:system-ui,sans-serif;padding:40px;color:#0f172a}h1{margin:0}table{width:100%;border-collapse:collapse;margin-top:20px}td,th{border-bottom:1px solid #e2e8f0;padding:10px;text-align:left}h2{color:#475569;font-weight:500}</style>
  </head><body>
  <h1>🌤️ Weather Report</h1>
  <h2>${b.place.name}${b.place.country ? ", " + b.place.country : ""} · ${new Date().toLocaleString()}</h2>
  <p><strong>${toUnit(b.current.temp, unit)}°${unit}</strong> — ${b.current.info.label}. Feels like ${toUnit(b.current.apparent, unit)}°.
  Humidity ${b.current.humidity}% · Wind ${b.current.wind} km/h · Pressure ${b.current.pressure} hPa · UV ${b.current.uv}.</p>
  <table><thead><tr><th>Day</th><th>Condition</th><th>High / Low</th><th>Rain</th></tr></thead><tbody>${rows}</tbody></table>
  <p style="margin-top:30px;color:#94a3b8;font-size:12px">Generated by Skyward · Data from Open-Meteo</p>
  </body></html>`;
  const w = window.open("", "_blank");
  if (w) {
    w.document.write(html);
    w.document.close();
    w.focus();
    setTimeout(() => w.print(), 400);
  }
}
